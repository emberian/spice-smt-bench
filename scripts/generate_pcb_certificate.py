#!/usr/bin/env python3
"""Untrusted search for a PCB forward-interval certificate checked by Lean decide.

No numerical result from Python is trusted: the generated file proves all
interval extensions and the exhaustive paving tree using IntervalCheck.
"""
from fractions import Fraction as Q
from pathlib import Path
import math
import re

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / 'benchmarks/smt2/smt2-exp/09a_pcb_microstrip_dfm_unsat.smt2').read_text()
tokens = re.findall(r'\(|\)|[^\s()]+', re.sub(r';[^\n]*', '', source))
pos = 0
def parse():
    global pos
    token = tokens[pos]; pos += 1
    if token != '(':
        return token
    xs = []
    while tokens[pos] != ')': xs.append(parse())
    pos += 1
    return xs
forms = []
while pos < len(tokens): forms.append(parse())
params = ['dw_etch', 'ds_etch', 'dh_lam', 't_cu', 'er_lam']
root = [(Q('-0.000008'), Q('0.000004')), (Q('-0.000004'), Q('0.000008')),
        (Q('-0.000005'), Q('0.000005')), (Q('0.000032'), Q('0.000038')), (Q('4.15'), Q('4.35'))]
defs = {}
physics = source.split('; --- Constitutive')[1].split('; --- Negated')[0]
# Track source conjunct positions for the generated-target bridge.
phys_forms = [f[1] for f in forms if f[0] == 'assert']
for form in phys_forms:
    if form[0] != '=': continue
    left, right = form[1:]
    if isinstance(left, str): defs[left] = ('direct', right)
    elif left[0] == 'exp' and isinstance(left[1], str): defs[left[1]] = ('logarithm', right)
    elif left[0] == '*' and left[1] == left[2] and isinstance(left[1], str): defs[left[1]] = ('squareRoot', right)

def symbols(e):
    if isinstance(e, list): return set().union(*(symbols(x) for x in e[1:]))
    try: Q(e); return set()
    except ValueError: return {e}
order = list(params)
def visit(name):
    if name in order: return
    for dep in sorted(symbols(defs[name][1])): visit(dep)
    order.append(name)
for target in ['Z0_tl50', 'Zdiff_diff90']: visit(target)
indices = {n:i for i,n in enumerate(order)}

def expr(e):
    if isinstance(e,str):
        if e in indices: return f'(.var {indices[e]})'
        return f'(.const {rat(Q(e))})'
    op = {'+':'add','-':'neg' if len(e)==2 else 'sub','*':'mul','/':'div','exp':'exp'}[e[0]]
    return f'(.{op} '+ ' '.join(expr(a) for a in e[1:])+')'
def rat(q): return f'⟨{q.numerator}, {q.denominator}, by decide⟩'
def iv(q): return f'⟨{rat(q[0])}, {rat(q[1])}⟩'
def ivlist(xs): return '['+', '.join(iv(x) for x in xs)+']'

def ev(e, env):
    if isinstance(e,str):
        if e in env: return env[e]
        f=float(Q(e)); return f,f
    args=[ev(x,env) for x in e[1:]]
    a,b=args[0]
    if e[0]=='exp':
        # Same rational scaling-and-squaring enclosures as QInterval.exp.
        return (1+a/256)**256, (1-b/256)**-256
    if len(args)==1: return -b,-a
    c,d=args[1]
    if e[0]=='+': return a+c,b+d
    if e[0]=='-': return a-d,b-c
    if e[0]=='/':
        assert c>0
        c,d=1/d,1/c
    vals=[a*c,a*d,b*c,b*d]
    return min(vals), max(vals)

def calculate(box):
    env={n:tuple(map(float,q)) for n,q in zip(params,box)}; cert=[]
    for name in order[5:]:
        kind, rhs=defs[name]; lo,hi=ev(rhs,env)
        if kind=='logarithm':
            lo=256*(-math.expm1(-math.log(lo)/256))
            hi=256*math.expm1(math.log(hi)/256)
        elif kind=='squareRoot': lo,hi=math.sqrt(lo), math.sqrt(hi)
        # Decimal widening makes every endpoint small and kernel computation fast.
        qlo=Q(math.floor((lo-1e-8)*1000000),1000000)
        qhi=Q(math.ceil((hi+1e-8)*1000000),1000000)
        cert.append((qlo,qhi)); env[name]=(float(qlo),float(qhi))
    good = env['Z0_tl50'][0]>=45 and env['Z0_tl50'][1]<=55 and env['Zdiff_diff90'][0]>=90 and env['Zdiff_diff90'][1]<=110
    return good,cert
certs=[]; visited=0
def search(box, depth=0):
    global visited
    visited+=1
    if visited>8191: raise RuntimeError('paving search budget exceeded')
    good,cert=calculate(box)
    if good:
        i=len(certs);certs.append(cert);return f'(.leaf {i})'
    i=depth%5;lo,hi=box[i];mid=(lo+hi)/2
    left=list(box);right=list(box);left[i]=(lo,mid);right[i]=(mid,hi)
    return f'(.split {i} {rat(mid)} {search(left,depth+1)} {search(right,depth+1)})'
tree=search(root)
print(f'PCB certificate: {visited} boxes, {len(certs)} leaves, {len(order)-5} forward definitions')
text=['import SpiceSmtBench.IntervalCheck', '', 'namespace SpiceSmtBench.Targets', 'open IntervalCheck',
      '', '-- Generated by scripts/generate_pcb_certificate.py; checked entirely by the kernel.',
      'def pcbDefinitions : List PDefinition := [']
text.append(',\n'.join(f'  ⟨.{defs[n][0]}, {expr(defs[n][1])}⟩' for n in order[5:]))
text += [']',f'def pcbRoot : List QInterval := {ivlist(root)}',
         f'def pcbRanges : List (Nat × QInterval) := [({indices["Z0_tl50"]}, {iv((Q(45),Q(55)))}), ({indices["Zdiff_diff90"]}, {iv((Q(90),Q(110)))})]',
         'def pcbCertificates : List (List QInterval) := [']
text.append(',\n'.join('  '+ivlist(c) for c in certs)); text += [']', f'def pcbTree : PavingTree := {tree}',
    'set_option maxRecDepth 20000 in', 'set_option maxHeartbeats 10000000 in',
    'theorem pcbReplay : verifyPaving (checkForwardLeaf 5 pcbDefinitions pcbRanges pcbCertificates) pcbTree pcbRoot = true := by decide',
    '', 'end SpiceSmtBench.Targets', '']
(ROOT/'lean/SpiceSmtBench/PcbCertificate.lean').write_text('\n'.join(text))


# The bridge uses the generated proposition's actual conjunct tree, never an
# assumed equation numbering or a trusted Python evaluation.
generated=(ROOT/'lean/SpiceSmtBench/TargetsGenerated.lean').read_text()
target=generated.split('def Bench_09a_pcb_microstrip_dfm_unsat')[1].split('\n/--')[0]
binders=re.search(r'∀ \((.*?) : R\),',target,re.S).group(1).split()
body=target.split(': R),',1)[1].strip()
def split_top(s, token):
    depth=0; start=0; parts=[]
    for i,c in enumerate(s):
        if c=='(': depth+=1
        elif c==')': depth-=1
        elif depth==0 and s.startswith(token,i):
            parts.append(s[start:i].strip());start=i+len(token)
    parts.append(s[start:].strip());return parts

def strip(s):
    while s.startswith('(') and s.endswith(')'):
        depth=0
        for i,c in enumerate(s):
            if c=='(': depth+=1
            elif c==')': depth-=1
            if depth==0: break
        if i!=len(s)-1: break
        s=s[1:-1].strip()
    return s
bounds,phys,unsafe=split_top(body,'→')
leaves=[]
def pattern(s):
    s=strip(s);parts=split_top(s,'∧')
    if len(parts)==1:
        name=f'h{len(leaves)}';leaves.append((name,s));return name
    return '⟨'+', '.join(pattern(p) for p in parts)+'⟩'
pat=pattern(phys)
def equation(name,kind):
    if kind=='direct': prefix=name+' ='
    elif kind=='logarithm': prefix=f'(TF.exp {name}) ='
    else: prefix=f'(TF.mul {name} {name}) ='
    return next(h for h,s in leaves if s.startswith(prefix))
def nonneg(name):
    return next(h for h,s in leaves if s==f'TF.le TF.zero {name}')
simp='PDefinition.holds, PExpr.eval, QRat.eval, env, List.getD, List.getElem?_cons_succ, List.getElem?_cons_zero, Option.getD_some, TF.zero_eq_ofRat, TF.one_eq_ofRat, TF.ofInt_eq_ofRat'
bridge=['-- BEGIN GENERATED PCB BRIDGE',
 '/-- Full continuous manufacturing-box proof by checked forward bounds and paving. -/',
 'theorem bench09a_pcb_microstrip_dfm_proved {R : Type} (TF : TranscendentalField R) :',
 '    Bench_09a_pcb_microstrip_dfm_unsat TF := by',
 '  intro '+' '.join(binders)+' hb hp hu',
 '  rcases hp with '+pat,
 '  let env : Nat → R := fun i => (['+', '.join(order)+'] : List R).getD i TF.zero',
 '  have hd : holdsDefinitions TF env 5 pcbDefinitions := by',
 '    change '+ ' ∧ '.join(f'(PDefinition.holds TF env {i} ⟨.{defs[n][0]}, {expr(defs[n][1])}⟩)' for i,n in enumerate(order) if i>=5)+' ∧ True',
 '    refine ⟨'+', '.join('?_' for _ in order[5:])+', trivial⟩']
for n in order[5:]:
    kind=defs[n][0];h=equation(n,kind)
    witness=f'And.intro {nonneg(n)} {h}' if kind=='squareRoot' else h
    bridge.append(f'    · simpa only [{simp}] using ({witness})')
bridge += ['  have hm : memBox TF pcbRoot env := by',
 '    rcases hb with ⟨p0, p1, p2, p3, p4, _⟩',
 '    simpa only [memBox, pcbRoot, memInterval, QRat.eval, env, List.getD, List.getElem?_cons_succ, List.getElem?_cons_zero, Option.getD_some] using (And.intro p0 (And.intro p1 (And.intro p2 (And.intro p3 (And.intro p4 True.intro)))))',
 '  have hn : ¬ holdsRanges TF env pcbRanges := by',
 '    intro hr',
 '    change (TF.le (TF.ofRat 45 1) Z0_tl50 ∧ TF.le Z0_tl50 (TF.ofRat 55 1)) ∧ (TF.le (TF.ofRat 90 1) Zdiff_diff90 ∧ TF.le Zdiff_diff90 (TF.ofRat 110 1)) ∧ True at hr',
 '    simp only [TF.ofInt_eq_ofRat] at hu',
 '    rcases hu with h | h | h | h',
 '    · exact ((TF.lt_iff_le_not_le _ _).mp h).2 hr.1.1',
 '    · exact ((TF.lt_iff_le_not_le _ _).mp h).2 hr.1.2',
 '    · exact ((TF.lt_iff_le_not_le _ _).mp h).2 hr.2.1.1',
 '    · exact ((TF.lt_iff_le_not_le _ _).mp h).2 hr.2.1.2',
 '  exact paving_unsat_sound TF (fun env => holdsDefinitions TF env 5 pcbDefinitions ∧ ¬ holdsRanges TF env pcbRanges)',
 '    (checkForwardLeaf 5 pcbDefinitions pcbRanges pcbCertificates)',
 '    (checkForwardLeaf_sound TF 5 pcbDefinitions pcbRanges pcbCertificates)',
 '    pcbTree pcbRoot env pcbReplay hm ⟨hd, hn⟩',
 '-- END GENERATED PCB BRIDGE']
p=ROOT/'lean/SpiceSmtBench/Targets.lean'
s=p.read_text()
s=re.sub(r'-- BEGIN GENERATED PCB BRIDGE.*?-- END GENERATED PCB BRIDGE\n?', '', s, flags=re.S)
s=s.replace('end SpiceSmtBench.Targets','\n'.join(bridge)+'\n\nend SpiceSmtBench.Targets')
s=re.sub(r'\n{3,}', '\n\n', s)
p.write_text(s)
